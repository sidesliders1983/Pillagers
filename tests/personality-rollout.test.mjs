import test from 'node:test';
import assert from 'node:assert/strict';
import {loadTypeScript} from '../scripts/load-typescript.mjs';
const core=loadTypeScript(new URL('../src/simulation/SimulationCore.ts',import.meta.url));
const {GameplaySession}=loadTypeScript(new URL('../src/gameplay-lab/GameplaySession.ts',import.meta.url));
const {SharedSettlement}=loadTypeScript(new URL('../src/play/SharedSettlement.ts',import.meta.url));
test('new player campaigns enable social behavior through the shared session without enabling CPU clans',()=>{
    const lab=new GameplaySession(32,1);
    assert.equal(lab.snapshot().social?.config.enabled,true);
    lab.newCampaign(17);
    assert.equal(lab.snapshot().social?.config.enabled,true);
    assert.ok(Object.values(lab.snapshot().world.targetClans).every(target=>target.social===undefined));
    const board=new SharedSettlement(32,1);
    assert.equal(board.session.snapshot().social?.config.enabled,true);
    board.newCampaign(17,true);
    assert.equal(board.session.snapshot().social?.config.enabled,true);
    const fjord=SharedSettlement.restore(board.handoff('fjord'),'fjord');
    assert.equal(fjord.session.snapshot().social?.config.enabled,true);
    assert.equal(core.createCampaign(32).social,undefined,'The low-level Core baseline stays explicit-off');
});
test('explicit off, legacy import and restart preserve saved rules; a genuinely new campaign uses new defaults',()=>{
    const off=new GameplaySession(32,1,false);
    assert.equal(off.snapshot().social,undefined);
    off.newCampaign(17,true,false);
    assert.equal(off.snapshot().social,undefined);
    off.restartCampaign(true);
    assert.equal(off.snapshot().social,undefined);
    off.restartCampaign(false,()=>41);
    assert.equal(off.snapshot().social,undefined);
    off.newCampaign(32);
    assert.equal(off.snapshot().social.config.enabled,true);
    const old=core.serializeState(core.createCampaign(32));
    off.loadJSON(old);
    assert.equal(off.saveJSON(),old);
    off.restartCampaign(true);
    assert.equal(off.snapshot().social,undefined);
    const owner=new SharedSettlement(32,1);
    owner.importJSON(old);
    const book=owner.session.book.snapshot();
    const transferred=SharedSettlement.restore(owner.handoff('fjord'),'fjord');
    assert.equal(transferred.session.saveJSON(),old);
    assert.deepEqual(transferred.session.book.snapshot(),book);
    transferred.restart(true);
    assert.equal(transferred.session.snapshot().social,undefined);
    transferred.newCampaign(17,false,false);
    assert.equal(transferred.session.snapshot().social,undefined);
    transferred.newCampaign(32,false);
    assert.equal(transferred.session.snapshot().social.config.enabled,true);
});
