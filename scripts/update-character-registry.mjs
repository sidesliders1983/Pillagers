import {readFileSync,writeFileSync} from 'node:fs';
import {loadTypeScript} from './load-typescript.mjs';
import {readGLB,geometryGLTF,measureGLB,publicFile} from './characters/glb-inspection.mjs';
const {characterAssets,validateCharacterRegistry}=loadTypeScript(new URL('../src/characters/CharacterAssets.ts',import.meta.url));
validateCharacterRegistry();
const measurements={},manifest={schemaVersion:1,assets:[]};
for(const asset of characterAssets){
    const lods={};
    for(const [lod,path] of Object.entries(asset.lods)){
        try{
            const record=readGLB(path);
            if(asset.type!=='body'){
                const provenance=JSON.parse(readFileSync(publicFile(path.replace('.glb','.provenance.json')),'utf8').replace(/^\uFEFF/,''));
                if(provenance.outputSha256!==record.sha256)throw new Error('stale output provenance');
            }
            const measured=measureGLB(record,await geometryGLTF(record));
            measurements[path]=measured;lods[lod]={file:path,...measured};
        }catch(error){throw new Error(`${asset.id} LOD${lod}: ${error.message}`,{cause:error});}
    }
    manifest.assets.push({...asset,lods});
}
// Only write after the entire declared library can be measured.
writeFileSync(new URL('../src/characters/CharacterAssetMeasurements.ts',import.meta.url),
`/** Generated by scripts/update-character-registry.mjs. Do not edit by hand. */
export interface AssetMeasurement {sha256:string;triangles:number;materials:number;bytes:number;bounds:{min:number[];max:number[]};}
export const characterAssetMeasurements:Record<string,AssetMeasurement>=${JSON.stringify(measurements,null,4)};
`);
writeFileSync(new URL('../public/character-assets.manifest.json',import.meta.url),JSON.stringify(manifest,null,2)+'\n');
console.log(`Measured ${Object.keys(measurements).length} GLBs in ${characterAssets.length} registered assets.`);
