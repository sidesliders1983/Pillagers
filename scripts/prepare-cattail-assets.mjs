import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {EXTMeshoptCompression, EXTTextureWebP} from '@gltf-transform/extensions';
import {dedup, getBounds} from '@gltf-transform/functions';
import sharp from 'sharp';
import {terrainIO} from './terrain-io.mjs';

assert.ok(process.argv[2], 'Supply the original Poly Pizza Cattail GLB.');
const original = await readFile(resolve(process.argv[2]));
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
assert.equal(sha256(original), '4274703fe73864749644939c94e7a03c53987322a2eee8556f684e78649b7eac',
    'This preparation is pinned to the selected Cattail, not an unrelated download.');
const io = await terrainIO(), document = await io.readBinary(original), root = document.getRoot();
const sourceBounds = getBounds(root.listScenes()[0]);
const height = sourceBounds.max[1] - sourceBounds.min[1];
const centerX = (sourceBounds.min[0] + sourceBounds.max[0]) / 2;
const centerZ = (sourceBounds.min[2] + sourceBounds.max[2]) / 2;
for (const mesh of root.listMeshes()) for (const primitive of mesh.listPrimitives()) {
    const accessor = primitive.getAttribute('POSITION'), positions = accessor.getArray().slice();
    for (let i = 0; i < positions.length; i += 3) {
        positions[i] = (positions[i] - centerX) / height;
        positions[i + 1] = (positions[i + 1] - sourceBounds.min[1]) / height;
        positions[i + 2] = (positions[i + 2] - centerZ) / height;
    }
    accessor.setArray(positions);
}
const textures = [];
document.createExtension(EXTTextureWebP).setRequired(true);
for (const texture of root.listTextures()) {
    const bytes = await sharp(texture.getImage()).resize(128, 128, {fit: 'inside', withoutEnlargement: true})
        .webp({quality: 90, effort: 4}).toBuffer();
    const info = await sharp(bytes).metadata();
    textures.push({width: info.width, height: info.height, bytes: bytes.length});
    texture.setImage(bytes).setMimeType('image/webp');
}
await document.transform(dedup());
const plain = await io.writeBinary(document);
// Keep normalized positions, normals and UVs exact; compression is optional.
const geometryHash = doc => sha256(JSON.stringify(doc.getRoot().listMeshes().flatMap(mesh =>
    mesh.listPrimitives().map(p => ({indices: [...p.getIndices().getArray()],
        attributes: p.listSemantics().sort().map(name => [name, ...p.getAttribute(name).getArray()])})))));
const expectedGeometry = geometryHash(document);
document.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({
    method: EXTMeshoptCompression.EncoderMethod.QUANTIZE});
const compressed = await io.writeBinary(document);
const exact = geometryHash(await io.readBinary(compressed)) === expectedGeometry;
const bytes = exact && compressed.length < plain.length ? compressed : plain;
const published = await io.readBinary(bytes), bounds = getBounds(published.getRoot().listScenes()[0]);
const triangles = published.getRoot().listMeshes().reduce((sum, mesh) => sum + mesh.listPrimitives()
    .reduce((n, p) => n + p.getIndices().getCount() / 3, 0), 0);
assert.equal(triangles, 473);
assert.ok(bytes.length < 65536);
const runtime = {file: 'cattail.glb', bytes: bytes.length, sha256: sha256(bytes), bounds, triangles,
    texturePixelsRGBA: textures.reduce((sum, t) => sum + t.width * t.height * 4, 0), textures,
    encoding: bytes === compressed ? 'meshopt-exact' : 'gltf-exact'};
const source = {url: 'https://poly.pizza/m/9vCk81sIPve', title: 'Cattail', author: 'Poly by Google',
    license: 'CC-BY-3.0', licenseUrl: 'https://creativecommons.org/licenses/by/3.0/',
    download: 'https://static.poly.pizza/049b2eb3-13d5-4b9a-85be-5dec11d97eb4.glb.br',
    bytes: original.length, sha256: sha256(original), bounds: sourceBounds, triangles};
const modifications = 'Grounded and centered at unit height; original triangle topology retained; 512px colour texture reduced to 128px WebP.';
const output = 'public/game-assets/wetlands';
await mkdir(output, {recursive: true});
await writeFile(output + '/cattail.glb', bytes);
await writeFile(output + '/cattail-manifest.json', JSON.stringify({version: 1, source, runtime, modifications}, null, 2) + '\n');
await writeFile(output + '/ATTRIBUTION.txt',
    'Cattail by Poly by Google\nhttps://poly.pizza/m/9vCk81sIPve\n' +
    'Licensed under Creative Commons Attribution 3.0: https://creativecommons.org/licenses/by/3.0/\n' +
    'Adaptations for FjordSide: ' + modifications + '\n\n' +
    'Procedural grass: boona13 / threejs-grass-water-shaders\n' +
    'https://github.com/boona13/threejs-grass-water-shaders\n\n' +
    await readFile('src/vendor/boona13-grass/LICENSE', 'utf8'));
await writeFile('src/fjord-play/CattailAssets.ts',
    '// Generated by scripts/prepare-cattail-assets.mjs.\nexport const cattailAsset = ' +
    JSON.stringify({path: 'game-assets/wetlands/cattail.glb', bytes: runtime.bytes, sha256: runtime.sha256,
        bounds, triangles, texturePixelsRGBA: runtime.texturePixelsRGBA}, null, 4) + ' as const;\n');
console.log(JSON.stringify({source, runtime}, null, 2));
