import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {dedup, prune, resample, meshopt, simplify, weld} from '@gltf-transform/functions';
import {MeshoptEncoder, MeshoptDecoder, MeshoptSimplifier} from 'meshoptimizer';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const source=resolve(root,'Assets/Characters/Human/Human-textured.glb'),output=resolve(root,'public/game-assets/human');
await Promise.all([MeshoptEncoder.ready,MeshoptDecoder.ready,MeshoptSimplifier.ready]);
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
const sourceBytes=await readFile(source),sha=bytes=>createHash('sha256').update(bytes).digest('hex'),lods=[];
await mkdir(output,{recursive:true});
for(const [level,ratio] of [[0,1],[1,.4],[2,.32]]){
 const document=await io.read(source),clips=document.getRoot().listAnimations().map(clip=>clip.getName());
 if(clips.length===0||!clips.includes('Walking')||!clips.includes('Running'))throw new Error('Unexpected source animation set');
 // Freeze one source coordinate frame before reduction; all LODs use this frame.
 const minimum=[Infinity,Infinity,Infinity],maximum=[-Infinity,-Infinity,-Infinity];
 for(const node of document.getRoot().listNodes()){
  const mesh=node.getMesh();if(!mesh)continue;const m=node.getWorldMatrix();
  for(const primitive of mesh.listPrimitives()){
   const positions=primitive.getAttribute('POSITION').getArray();
   for(let i=0;i<positions.length;i+=3){
    const x=positions[i],y=positions[i+1],z=positions[i+2];
    const point=[m[0]*x+m[4]*y+m[8]*z+m[12],m[1]*x+m[5]*y+m[9]*z+m[13],m[2]*x+m[6]*y+m[10]*z+m[14]];
    for(let axis=0;axis<3;axis++){minimum[axis]=Math.min(minimum[axis],point[axis]);maximum[axis]=Math.max(maximum[axis],point[axis]);}
   }
  }
 }
 const frame={height:maximum[1]-minimum[1],offset:[-(minimum[0]+maximum[0])/2,-minimum[1],-(minimum[2]+maximum[2])/2]};
 if(!Number.isFinite(frame.height)||frame.height<=0)throw new Error('Invalid source frame');
 for(const scene of document.getRoot().listScenes())scene.setExtras({...scene.getExtras(),pillagersFrame:frame});

 await document.transform(dedup(),resample({tolerance:1e-7}));
 if(ratio<1)await document.transform(weld(),simplify({simplifier:MeshoptSimplifier,ratio,error:.002,lockBorder:true}));
 await document.transform(prune(),meshopt({encoder:MeshoptEncoder,level:'medium'}));
 const bytes=await io.writeBinary(document),file='Human_LOD'+level+'.glb',checked=await io.readBinary(bytes);
 if(checked.getRoot().listAnimations().length!==clips.length||checked.getRoot().listSkins().length!==1)throw new Error('Export lost rig or clips');
 const triangles=checked.getRoot().listMeshes().reduce((sum,mesh)=>sum+mesh.listPrimitives().reduce((total,p)=>total+(p.getIndices()?.getCount()??p.getAttribute('POSITION').getCount())/3,0),0);
 await writeFile(resolve(output,file),bytes);lods.push({level,file,triangles,bytes:bytes.length,sha256:sha(bytes)});
}
const clipsFromSource=(await io.read(source)).getRoot().listAnimations().map(clip=>clip.getName());
const manifest={schemaVersion:1,source:'Assets/Characters/Human/Human-textured.glb',sourceSha256:sha(sourceBytes),sourceBytes:sourceBytes.length,rig:'SmartRigArmature',morphology:false,appearance:false,textures:'authored Meshy textures',animations:clipsFromSource,lods};
await writeFile(resolve(output,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');console.log(JSON.stringify(manifest,null,2));



await writeFile(resolve(root,'src/characters/MeshyHumanAssetIdentity.ts'),'// Provenance of prepared runtime assets; regenerated by assets:human.\nexport const meshyHumanAssetIdentity='+JSON.stringify(lods.map(l=>({path:'/game-assets/human/'+l.file,sha256:l.sha256})),null,2)+' as const;\nexport const meshyHumanAvailableClips='+JSON.stringify(clipsFromSource,null,2)+' as const;\n');

