import assert from 'node:assert/strict';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { NodeIO } from '@gltf-transform/core';
import { prune } from '@gltf-transform/functions';
import sharp from 'sharp';

const root = fileURLToPath(new URL('../', import.meta.url));
const sourceRoot = resolve(process.argv[2] ?? join(root, 'Assets/Wedding-ceremony'));
const output = join(root, 'public/game-assets/wedding');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const slots = [
    ['wedding-lyre', 'Meshy_AI_viking_instrument_lyr_1027065406_image-to-3d-texture.glb'],
    ['wedding-flute', 'Meshy_AI_viking_instrument_bon_1027065426_image-to-3d-texture.glb'],
    ['wedding-frame-drum', 'Meshy_AI_viking_instrument_fra_1027065354_image-to-3d-texture.glb'],
    ['wedding-book', 'wedding_book.glb'],
    ['wedding-crown', 'wedding-flower.glb'],
];
mkdirSync(output, { recursive: true });
const io = new NodeIO();
const props = [];
for (const [id, source] of slots) {
    const bytes = readFileSync(join(sourceRoot, source));
    const doc = await io.readBinary(bytes);
    const materials = doc.getRoot().listMaterials();
    assert.equal(materials.length, 1);
    for (const material of materials) {
        material.setNormalTexture(null).setMetallicRoughnessTexture(null).setOcclusionTexture(null)
            .setRoughnessFactor(.92).setMetallicFactor(0);
        const colour = material.getBaseColorTexture();
        assert.ok(colour?.getImage());
        colour.setImage(await sharp(colour.getImage()).resize(512, 512, { fit: 'inside' }).jpeg({ quality: 85, chromaSubsampling: '4:4:4' }).toBuffer());
        colour.setMimeType('image/jpeg');
    }
    await doc.transform(prune());
    const prepared = await io.writeBinary(doc);
    const file = id + '.glb';
    writeFileSync(join(output, file), prepared);
    props.push({ id, file, bytes: prepared.byteLength, sha256: hash(prepared), source,
        sourceBytes: bytes.length, sourceSHA256: hash(bytes), geometry: 'Original Meshy topology/normals/UVs; one 512px colour texture; no extra rig.' });
}

/** Read actual MPEG Layer III frame durations; browser metadata remains playback authority. */
function mp3Duration(bytes) {
    let offset = bytes.toString('ascii', 0, 3) === 'ID3' ?
        10 + ((bytes[6] & 127) << 21 | (bytes[7] & 127) << 14 | (bytes[8] & 127) << 7 | bytes[9] & 127) : 0;
    let seconds = 0, frames = 0;
    while (offset + 4 <= bytes.length) {
        const header = bytes.readUInt32BE(offset);
        const version = header >>> 19 & 3, layer = header >>> 17 & 3;
        const rateIndex = header >>> 10 & 3, bitIndex = header >>> 12 & 15;
        if ((header >>> 21) !== 2047 || version === 1 || layer !== 1 || rateIndex === 3 || !bitIndex || bitIndex === 15) { offset++; continue; }
        const rate = [44100, 48000, 32000][rateIndex] / (version === 3 ? 1 : version === 2 ? 2 : 4);
        const bitrate = (version === 3 ? [0,32,40,48,56,64,80,96,112,128,160,192,224,256,320] :
            [0,8,16,24,32,40,48,56,64,80,96,112,128,144,160])[bitIndex];
        const length = Math.floor((version === 3 ? 144000 : 72000) * bitrate / rate) + (header >>> 9 & 1);
        if (offset + length > bytes.length) break;
        seconds += (version === 3 ? 1152 : 576) / rate;
        frames++;
        offset += length;
    }
    assert.ok(frames > 100 && seconds > 5 && seconds < 180, 'Unexpected selected music duration');
    return { seconds: Math.round(seconds * 1000) / 1000, frames };
}
