import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { meshopt, prune, resample } from '@gltf-transform/functions';
import { MeshoptDecoder, MeshoptEncoder } from 'meshoptimizer';

const original = 'Assets/Characters/Human/Human-textured.glb';
const source = 'Assets/Characters/Human/Human-textured-v2.glb';
const output = 'public/game-assets/human/Human_ExtraAnimations.glb';
const names = ['Archery_Shot_1', 'Archery_Shot_2', 'Heavy_Hammer_Swing', 'Sit_and_Doze_Off'];
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const originalBytes = await readFile(original), sourceBytes = await readFile(source);
const json = bytes => JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)));
assert.deepEqual(json(sourceBytes).nodes, json(originalBytes).nodes,
    'Additional animations require exactly the existing source hierarchy and transforms');
await Promise.all([MeshoptEncoder.ready, MeshoptDecoder.ready]);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
    'meshopt.encoder': MeshoptEncoder, 'meshopt.decoder': MeshoptDecoder,
});
const document = await io.readBinary(sourceBytes), base = await io.readBinary(originalBytes);
assert.deepEqual(document.getRoot().listSkins()[0].getInverseBindMatrices().getArray(),
    base.getRoot().listSkins()[0].getInverseBindMatrices().getArray());
for (const animation of document.getRoot().listAnimations())
    if (!names.includes(animation.getName())) animation.dispose();
assert.deepEqual(document.getRoot().listAnimations().map(a => a.getName()), names);
for (const node of document.getRoot().listNodes()) { node.setMesh(null); node.setSkin(null); }
for (const mesh of document.getRoot().listMeshes()) mesh.dispose();
for (const skin of document.getRoot().listSkins()) skin.dispose();
await document.transform(prune({ keepLeaves: true }), resample({ tolerance: 1e-7 }),
    meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
const bytes = await io.writeBinary(document);
await writeFile(output, bytes);
const identity = { path: '/game-assets/human/Human_ExtraAnimations.glb', sha256: sha(bytes),
    source, sourceSha256: sha(sourceBytes), bodySourceSha256: sha(originalBytes), clips: names };
await writeFile('src/characters/HumanExtraAnimations.ts',
    '// Verified additive clips; generated by prepare-human-extra-animations.mjs.\n' +
    'export const humanExtraAnimations = ' + JSON.stringify(identity, null, 4) + ' as const;\n');
await writeFile('public/game-assets/human/extra-animations.json',
    JSON.stringify({ ...identity, bytes: bytes.length, sourceBytes: sourceBytes.length }, null, 2) + '\n');
console.log(JSON.stringify({ ...identity, bytes: bytes.length }, null, 2));
