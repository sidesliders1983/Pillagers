import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { loadTypeScript } from '../load-typescript.mjs';

const source = process.argv[2];
assert.ok(source, 'Pass the retained prepared-candidate directory. Originals are never changed.');
const input = resolve(source);
const output = resolve('public/game-assets/audio');
const plan = JSON.parse(readFileSync(new URL('./release-001.json', import.meta.url)));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const catalogueBytes = readFileSync(join(input, 'catalogue.json'));
assert.equal(hash(catalogueBytes), plan.sourceCatalogueSHA256, 'Candidate catalogue changed since acceptance');
const candidates = JSON.parse(catalogueBytes);
const { settlementReviewPack: manifest } = loadTypeScript(new URL('../../src/audio/SettlementSoundPack.ts', import.meta.url));
const entries = manifest.assets.map(asset => {
    const candidate = candidates.entries.find(entry => entry.id === asset.id);
    assert.ok(candidate, 'Accepted candidate missing: ' + asset.id);
    assert.equal(asset.path, 'game-assets/audio/' + candidate.prepared.file);
    assert.match(candidate.prepared.file, /^[a-z0-9-]+[.]wav$/);
    const bytes = readFileSync(join(input, candidate.prepared.file));
    assert.equal(hash(bytes), candidate.prepared.sha256, 'Prepared bytes changed: ' + asset.id);
    assert.equal(bytes.length, candidate.prepared.bytes);
    const entry = structuredClone(candidate);
    entry.status = { technical: 'prepared', listening: 'accepted', distribution: 'cleared' };
    const provider = entry.provenance.provider.startsWith('Pixabay') ? 'Pixabay' : 'ElevenLabs';
    entry.provenance.licenseEvidence = plan.licenseEvidence[provider];
    assert.ok(entry.provenance.licenseEvidence?.length, 'Missing provider evidence');
    if (provider === 'ElevenLabs') {
        // The private Flow/account link and raw provider receipt are not publication inputs.
        entry.provenance.sourceUrl = 'https://elevenlabs.io/sound-effects';
        delete entry.provenance.parameters;
        delete entry.provenance.prompt;
    }
    if (entry.id === 'lynx') entry.provenance.reviewNotes = [plan.ownerAcceptance.lynx];
    return entry;
});
// Verify every accepted source before writing any publication file.
mkdirSync(output, { recursive: true });
for (const entry of entries) copyFileSync(join(input, entry.prepared.file), join(output, entry.prepared.file));
const catalogue = { ...candidates, entries, release: plan, sourceCatalogueSHA256: hash(catalogueBytes) };
writeFileSync(join(output, 'catalogue.json'), JSON.stringify(catalogue, null, 2) + '\n');
writeFileSync(join(output, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(join(output, 'release.json'), JSON.stringify({ output: 'public/game-assets/audio' }, null, 2) + '\n');
writeFileSync('src/audio/PublishedSoundPack.ts',
    "import type { SoundManifest } from './FjordAudio';\n\n" +
    '/** Generated by scripts/audio/publish.mjs from the accepted release catalogue. */\n' +
    'export const publishedSoundPack: SoundManifest = ' + JSON.stringify(manifest, null, 4) + ';\n');
console.log(JSON.stringify({ assets: entries.length, bytes: entries.reduce((sum, entry) => sum + entry.prepared.bytes, 0),
    sourceCatalogueSHA256: hash(catalogueBytes) }));
