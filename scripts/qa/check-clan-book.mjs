import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)('C:/Users/Devoteam/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const origin = process.env.QA_ORIGIN || 'http://127.0.0.1:5180';
const output = 'docs/qa/clan-book';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const errors = [];
try {
    const page = await browser.newPage({ viewport: { width: 1024, height: 768 }, hasTouch: true });
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(() => {
        window.qaHidden = false;
        Object.defineProperty(document, 'hidden', { configurable: true, get: () => window.qaHidden });
    });
    await page.goto(origin + '/play?seed=17');
    await page.locator('#clan-book-reader:not([hidden])').waitFor({ timeout: 5000 });
    const opening = await page.locator('#clan-book-story').innerText();
    await page.locator('#play-settings > summary').click();
    const [download] = await Promise.all([page.waitForEvent('download'), page.locator('[data-action="export-book"]').click()]);
    const rollback = await readFile(await download.path());
    await page.locator('#play-settings > summary').click();
    assert.ok(opening.includes('Winter 800'));
    assert.equal(await page.locator('[data-action="run"]').innerText(), 'Start');
    const tickBefore = await page.locator('#play-hud').innerText();
    await page.locator('[data-action="run"]').click();
    await page.waitForTimeout(1200);
    assert.notEqual(await page.locator('#play-hud').innerText(), tickBefore, 'The canonical tick actually advances behind the reader');
    assert.equal(await page.locator('[data-action="run"]').innerText(), 'Pause');
    assert.equal(await page.locator('#clan-book-story').innerText(), opening, 'Displayed story remains frozen while running');
    await page.locator('[data-action="run"]').click();
    for (let i = 0; i < 5; i++) await page.getByRole('button', { name: '+1 Winter', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#clan-book-chapter').options.length === 2);
    assert.equal(await page.locator('#clan-book-story').innerText(), opening, 'New due chapter queues without replacing the current passage');
    await page.selectOption('#clan-book-chapter', '1');
    const chapter = await page.locator('#clan-book-story').innerText();
    assert.ok(chapter.includes('805'));
    await page.screenshot({ path: output + '/chapter-tablet.png' });
    await page.locator('#clan-book-appendix > summary').click();
    await page.locator('#clan-book-appendix table').scrollIntoViewIfNeeded();
    assert.ok((await page.locator('#clan-book-appendix table').innerText()).includes('Actual consumption'));
    await page.screenshot({ path: output + '/ledger-tablet.png' });
    await page.locator('#clan-book-appendix > summary').click();
    await page.locator('#clan-book-close').click();
    assert.equal(await page.locator('[data-action="run"]').innerText(), 'Start');
    await page.reload();
    assert.equal(await page.locator('#clan-book-reader').isVisible(), false, 'Reload does not repeat notified chapters');
    await page.locator('#play-settings > summary').click();
    await page.locator('#clan-book-open').click();
    await page.selectOption('#clan-book-chapter', '1');
    assert.equal(await page.locator('#clan-book-story').innerText(), chapter);
    await page.locator('#clan-book-close').press('Escape');
    assert.equal(await page.locator('#clan-book-reader').isVisible(), false);
    await page.locator('a[data-settlement-view="fjord"]').click();
    await page.locator('#fjord-canvas[data-ready="true"]').waitFor({ timeout: 120000 });
    assert.equal(await page.locator('#clan-book-reader').isVisible(), false, 'Handoff does not repeat notifications');
    await page.locator('#fjord-menu > summary').click();
    await page.locator('#clan-book-open').click();
    await page.selectOption('#clan-book-chapter', '1');
    assert.equal(await page.locator('#clan-book-story').innerText(), chapter);
    assert.equal(await page.locator('#fjord-run').innerText(), 'Start');
    await page.locator('#fjord-run').click();
    const startTick = await page.locator('#fjord-canvas').getAttribute('data-time');
    await page.waitForTimeout(1300);
    assert.notEqual(await page.locator('#fjord-canvas').getAttribute('data-time'), startTick);
    assert.equal(await page.locator('#clan-book-story').innerText(), chapter);
    await page.locator('#fjord-run').click();
    await page.setViewportSize({ width: 390, height: 844 });
    const box = await page.locator('#clan-book-reader').boundingBox();
    assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y + box.height <= 844);
    await page.screenshot({ path: output + '/chapter-phone.png' });
    await page.locator('#fjord-import').setInputFiles({ name: 'rollback.json', mimeType: 'application/json', buffer: rollback });
    await page.locator('#fjord-notice').filter({ hasText: 'Campaign imported, paused.' }).waitFor();
    await page.waitForFunction(() => document.querySelector('#clan-book-chapter').options.length === 1);
    assert.equal(await page.locator('#clan-book-chapter option').count(), 1);
    assert.equal(await page.locator('#clan-book-story').innerText(), opening, 'Rollback removes stale passage even with the same book identity');
    await page.locator('#fjord-run').click();
    await page.evaluate(() => { window.qaHidden = true; document.dispatchEvent(new Event('visibilitychange')); });
    const hiddenTime = await page.locator('#fjord-canvas').getAttribute('data-time');
    await page.waitForTimeout(1300);
    assert.equal(await page.locator('#fjord-canvas').getAttribute('data-time'), hiddenTime);
    await page.evaluate(() => { window.qaHidden = false; document.dispatchEvent(new Event('visibilitychange')); });
    assert.equal(await page.locator('#fjord-run').innerText(), 'Start');
    assert.equal(await page.locator('#clan-book-story').innerText(), opening);
    assert.deepEqual(errors, []);
    await writeFile(output + '/browser.json', JSON.stringify({ passed: true, errors,
        checks: ['opening popup', 'no automatic pause/resume', 'ordered chapters', 'frozen passage', 'refresh deduplication', 'menu reread', 'keyboard dismissal', 'tablet/phone touch layout', '2D/Fjord shared reader', 'same-book rollback', 'hidden-tab guard', 'real Core ticks behind reader'] }, null, 2));
} finally { await browser.close(); }
