import assert from 'node:assert/strict';
import { loadTypeScript } from '../load-typescript.mjs';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = createRequire(import.meta.url)('C:/Users/Devoteam/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const output = 'docs/qa/housing-lore';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const errors = [];
try {
    const page = await browser.newPage({ viewport: { width: 1280, height: 960 }, hasTouch: true });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:5180/play?seed=32');
    await page.locator('#clan-book-close').click();
    await page.selectOption('#entity-picker', 'household:founder-9');
    if (process.env.QA_BEFORE) await page.screenshot({ path: output + '/panel-before.png' });
    assert.equal(await page.locator('#entity-panel h2').innerText(), 'Daugirdė’s household');
    await page.selectOption('#entity-picker', 'longship:founding-longship');
    await page.getByRole('button', { name: 'Salvage longship (20 Materials)', exact: true }).click();
    await page.selectOption('#entity-picker', 'household:founder-9');
    await page.getByRole('button', { name: 'Build house (10 Materials)', exact: true }).click();
    await page.selectOption('#entity-picker', 'building:house-1');
    assert.equal(await page.locator('#entity-panel h2').innerText(), 'Daugirdė’s home');
    assert.ok((await page.locator('#entity-panel').innerText()).includes('Household: Daugirdė’s household'));
    assert.equal(await page.locator('#residence option:checked').innerText(), 'Daugirdė’s home');
    await page.locator('#entity-panel').evaluate(element => element.scrollTop = 0);
    await page.screenshot({ path: output + '/panel-after.png' });
    for (let i = 0; i < 5; i++) await page.getByRole('button', { name: '+1 Winter', exact: true }).click();
    await page.locator('#clan-book-reader:not([hidden])').waitFor();
    const text = await page.locator('#clan-book-story').innerText();
    assert.ok(text.includes('Daugirdė’s home was completed for Daugirdė’s household for 10 Materials.'));
    assert.doesNotMatch(text, /house-\d|household-\d|founder-\d|tent-founder/);
    await page.screenshot({ path: output + '/chapter-after.png' });
    await page.locator('#clan-book-close').click();
    await page.locator('a[data-settlement-view="fjord"]').click();
    await page.locator('#fjord-canvas[data-ready="true"]').waitFor({ timeout: 120000 });
    await page.getByText('Settlement identities', { exact: true }).click();
    await page.locator('#fjord-management [data-kind="building"][data-id="house-1"]').click();
    assert.equal(await page.locator('#entity-panel h2').innerText(), 'Daugirdė’s home');
    await page.screenshot({ path: output + '/fjord-after.png' });
    await page.locator('#fjord-run').click();
    const timeBeforeReading = await page.locator('#fjord-canvas').getAttribute('data-time');
    await page.locator('#fjord-menu > summary').click();
    await page.locator('#clan-book-open').click();
    await page.selectOption('#clan-book-chapter', '1');
    assert.equal(await page.locator('#clan-book-story').innerText(), text);
    await page.selectOption('#clan-book-chapter', '0');
    await page.locator('#clan-book-appendix > summary').click();
    const facts = await page.locator('#clan-book-appendix > div').innerText();
    assert.ok(facts.includes('Daugirdė’s household'));
    assert.ok(facts.includes('Housing source identities'));
    await page.waitForFunction(before => document.querySelector('#fjord-canvas').getAttribute('data-time') !== before, timeBeforeReading);
    assert.equal(await page.locator('#fjord-run').innerText(), 'Pause');
    await page.locator('#fjord-run').click();
    await page.locator('#clan-book-close').click();
    await page.reload();
    await page.locator('#fjord-canvas[data-ready="true"]').waitFor({ timeout: 120000 });
    assert.equal(await page.locator('#clan-book-reader').isVisible(), false);
    const securePage = await browser.newPage({ viewport: { width: 1280, height: 960 } });
    securePage.on('pageerror', error => errors.push(error.message));
    await securePage.goto('http://127.0.0.1:5180/play?seed=32');
    await securePage.locator('#clan-book-close').click();
    const core = loadTypeScript(new URL('../../src/simulation/SimulationCore.ts', import.meta.url));
    const fixture = core.createCampaign(32, { initialMaterials: 500, initialFood: 500, foundingCoupleChanceBps: 0 },
        { fertilityChanceBps: 0, partnershipChanceBps: 0 }, { enabled: false });
    const culturalName = 'Daugirdė <img src=x onerror="window.nameInjected=true"> & Sigrid';
    fixture.personas['founder-9'].name = culturalName;
    await securePage.locator('#import-file').setInputFiles({ name: 'housing-escape.json',
        mimeType: 'application/json', buffer: Buffer.from(core.serializeState(fixture)) });
    await securePage.getByText('Campaign loaded, paused.', { exact: true }).waitFor();
    await securePage.selectOption('#entity-picker', 'household:founder-9');
    assert.equal(await securePage.locator('#entity-panel h2').innerText(), culturalName + '’s household');
    assert.equal(await securePage.locator('#entity-panel img').count(), 0);
    await securePage.getByRole('button', { name: 'Build house (10 Materials)', exact: true }).click();
    for (let i = 0; i < 5; i++) await securePage.getByRole('button', { name: '+1 Winter', exact: true }).click();
    await securePage.locator('#clan-book-reader:not([hidden])').waitFor();
    assert.ok((await securePage.locator('#clan-book-story').innerText()).includes(culturalName + '’s home'));
    assert.equal(await securePage.locator('#clan-book-story img').count(), 0);
    assert.equal(await securePage.evaluate(() => window.nameInjected), undefined);
    await securePage.close();
    assert.deepEqual(errors, []);
    await writeFile(output + '/browser.json', JSON.stringify({ passed: true, errors,
        checks: ['resident household/home names', 'canonical picker values', 'historical chapter labels', '2D/Fjord names and saved text', 'refresh notification deduplication', 'tablet touch layout', 'clock continues while reading', 'cultural spelling and HTML escaping'] }, null, 2));
} finally { await browser.close(); }
