import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {loadTypeScript} from '../load-typescript.mjs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.argv[2]?process.argv[2]+'/playwright':'playwright');
const core=loadTypeScript(new URL('../../src/simulation/SimulationCore.ts',import.meta.url));
const output=new URL('../../artifacts/qa/persona-mortality/',import.meta.url);mkdirSync(output,{recursive:true});
let state=core.createSettlement(41,{fertilityChanceBps:0,partnershipChanceBps:0,careerReviewWinters:0,mortalityBands:[{minAge:0,chanceBps:0},{minAge:33,chanceBps:10000}]});
state=core.applyCommand(state,{type:'AssignOccupation',personaId:'einar',occupation:'farmer'});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://127.0.0.1:5180/gameplay-lab');
 await page.getByRole('heading',{name:'Pillagers · Gameplay Lab'}).waitFor();
 await page.locator('#import-file').setInputFiles({name:'mortality.json',mimeType:'application/json',buffer:Buffer.from(core.serializeState(state))});
 await page.locator('#person-einar').waitFor();
 assert.equal(await page.locator('#occupation-einar').isDisabled(),false);
 await page.getByRole('button',{name:'+1 Winter',exact:true}).click();
 const person=page.locator('#person-einar');
 assert.match(await person.innerText(),/Died in Winter 801 · Age at death: 33 Winters/);
 assert.equal(await person.getByRole('button',{name:'Assign occupation',exact:true}).isDisabled(),true);
 assert.equal(await page.locator('#occupation-einar').isDisabled(),true);
 assert.equal(await person.getByRole('button',{name:'Autonomy',exact:true}).count(),0);
 await person.getByRole('button',{name:'View lineage',exact:true}).click();
 assert.match(await page.locator('#lineage-view').innerText(),/Family groups: family/);
 assert.match(await page.locator('#lineage-view').innerText(),/Astrid/);
 await page.locator('#history-einar summary').click();
 assert.match(await page.locator('#history-einar').innerText(),/801:0/);
 await page.getByRole('button',{name:'Save locally',exact:true}).click();
 await page.getByRole('button',{name:'+1 Winter',exact:true}).click();
 assert.match(await person.innerText(),/Age at death: 33 Winters/);
 await page.getByRole('button',{name:'Load locally',exact:true}).click();
 assert.match(await page.locator('header').innerText(),/WINTER 801/);
 assert.match(await person.innerText(),/Age at death: 33 Winters/);
 assert.deepEqual(errors,[]);
 await person.scrollIntoViewIfNeeded();
 await page.screenshot({path:fileURLToPath(new URL('deceased-resident.png',output))});
 const report={status:'PASS',checks:['Canonical death via public import and AdvanceWinter','Age at death and Winter visible','Occupation actions disabled; autonomy absent','Lineage and closed work history retained','Save/load preserves death and frozen age'],errors};
 writeFileSync(new URL('browser-report.json',output),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
