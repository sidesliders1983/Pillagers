import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import ts from 'typescript';
import { loadTypeScript } from '../../scripts/load-typescript.mjs';
const revision = 'da0c7c6e6a739819a18f8cb4306508e02be2220d';
const root = fileURLToPath(new URL('../../', import.meta.url));
const native = createRequire(import.meta.url), cache = new Map();
function baseline(url) {
    const key = url.href;
    if (cache.has(key)) return cache.get(key);
    const module = { exports: {} };
    cache.set(key, module.exports);
    const path = relative(root, fileURLToPath(url)).replaceAll('\\', '/');
    const source = execFileSync('git', ['show', revision + ':' + path], { cwd: root, encoding: 'utf8' });
    const compiled = ts.transpileModule(source, { compilerOptions: {
        module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022,
    } }).outputText;
    new Function('require', 'module', 'exports', compiled)(
        name => name.startsWith('.') ? baseline(new URL(name + '.ts', url)) : native(name), module, module.exports);
    return module.exports;
}
const previous = baseline(new URL('../../src/world-generation/GenerateWorld.ts', import.meta.url));
const { parseWorld } = loadTypeScript(new URL('../../src/world-generation/WorldSave.ts', import.meta.url));
const old = previous.generateWorld({ seed: 18, preset: 'island', generatorVersion: 'fjordside-island-v0.3e' });
const loaded = parseWorld(JSON.stringify({ schemaVersion: 1, blueprint: old }));
assert.deepEqual(loaded, old);
const hash = createHash('sha256').update(JSON.stringify(old)).digest('hex');
await mkdir('scratch/settlement-sites-refinement', { recursive: true });
await writeFile('scratch/settlement-sites-refinement/old-save-check.json', JSON.stringify({
    sourceRevision: revision, seed: 18, version: old.config.generatorVersion,
    exactBlueprintPreserved: true, hash, source: 'Generated by the original committed source via git show, then parsed by current code.',
}, null, 2));
console.log('Original PR-head v0.3e save preserved byte-for-byte after JSON round-trip.');
