import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {loadTypeScript} from '../load-typescript.mjs';
const load = file => loadTypeScript(new URL('../../src/' + file + '.ts', import.meta.url));
const {campaignIslandCatalog} = load('fjord-play/BakedIslandCatalog');
const {adoptCampaignIsland, islandRecipe} = load('fjord-play/CampaignIsland');
const {SharedSettlement} = load('play/SharedSettlement');
const {newFjordScenario} = load('fjord-play/FjordScenario');
const {geographyIdentity} = load('fjord-play/FjordProjection');
const core = load('simulation/SimulationCore');
const entry = campaignIslandCatalog.entries.find(e => e.version === 'island-pool-v3' && e.seed === 18);
const payload = JSON.parse(gunzipSync(readFileSync('public' + entry.path)));
const seed = Array.from({length:100},(_,i)=>i).find(seed => islandRecipe(seed).seed === 18);
adoptCampaignIsland(seed, payload.world, payload.plan);
const shared = new SharedSettlement(newFjordScenario(seed), undefined, true, 'island-pool-v3');
shared.fjord.prepareMining(); shared.fjord.enableDiscovery();
shared.session.initializeMining(shared.fjord.blueprint, geographyIdentity(shared.fjord.blueprint));
const site = shared.session.readSnapshot().mining.sites[0];
const scout = Object.keys(shared.session.readSnapshot().personas).find(id => core.personaAge(shared.session.readSnapshot(), id) >= 18);
shared.command({type:'CreateExplorationGroup'});
shared.command({type:'SetExplorationMember',groupId:'group-1',personaId:scout,included:true});
shared.command({type:'StartExpedition',groupId:'group-1'});
shared.command({type:'ExploreArea',groupId:'group-1',target:site.approach});
shared.command({type:'AdvanceTicks',ticks:350});
shared.session.setRunning(false);
const text = shared.persist();
SharedSettlement.restore(text, 'fjord');
mkdirSync('docs/qa/mining-223', {recursive:true});
writeFileSync('docs/qa/mining-223/scouted-campaign.json',text);
writeFileSync('docs/qa/mining-223/review-context.json',JSON.stringify({seed,siteId:site.id,position:site.position,
    note:'One actual eight-Food scout has reached the outcrop. No Food, ore or discovery was injected.'},null,2));
console.log(JSON.stringify({seed,siteId:site.id,bytes:text.length}));
