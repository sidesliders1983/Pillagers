import {readdirSync,readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,relative} from 'node:path';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url)),publicRoot=join(root,'public'),versions={};
function visit(folder){
    for(const entry of readdirSync(folder,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))){
        const path=join(folder,entry.name);
        if(entry.isDirectory()){visit(path);continue;}
        if(!entry.name.endsWith('.provenance.json'))continue;
        const record=JSON.parse(readFileSync(path,'utf8').replace(/^\uFEFF/,''));
        if(!record.outputSha256)continue;
        const model=path.replace('.provenance.json','.glb'),hash=createHash('sha256').update(readFileSync(model)).digest('hex');
        assert.equal(hash,record.outputSha256,`Stale provenance: ${model}`);
        versions['/'+relative(publicRoot,model).replaceAll('\\','/')]=hash.slice(0,12);
    }
}
visit(join(publicRoot,'appearance'));
writeFileSync(join(root,'src/character-lab/AppearanceAssetVersions.ts'),
`/** Generated by scripts/update-appearance-versions.mjs; cache identity follows published geometry. */
const versions:Record<string,string>=${JSON.stringify(versions,null,4)};
export function versionedAppearanceAsset(path:string){
    const version=versions[path];
    if(!version)throw new Error(\`Missing published appearance version: \${path}\`);
    return \`\${path}?v=\${version}\`;
}
`);
console.log(`Versioned ${Object.keys(versions).length} published appearance assets.`);
