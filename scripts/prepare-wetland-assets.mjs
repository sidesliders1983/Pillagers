import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {basename,resolve} from 'node:path';
import sharp from 'sharp';
const source=resolve(process.argv[2]);
const bytes=await readFile(source), metadata=await sharp(bytes).metadata();
const directory='public/game-assets/wetlands';await mkdir(directory,{recursive:true});
const runtime=await sharp(bytes).resize(256,256,{fit:'fill'}).webp({quality:85,effort:6}).toBuffer();
const sha256=bytes=>createHash('sha256').update(bytes).digest('hex');
const manifest={version:1,source:{file:basename(source),bytes:bytes.length,sha256:sha256(bytes),width:metadata.width,height:metadata.height,
    generation:'Built-in image_gen; owner-approved generated pattern',
    prompt:'Seamless top-down Nordic bog base-color texture: interconnected damp chocolate-brown peat, muted olive moss, sedge roots and irregular dark wet depressions. Flat diffuse light, no cast shadows, no isolated discs or regular grid. Readable at 256 pixels; no ore, objects, text or borders.'},
    runtime:{file:'bog-ground.webp',bytes:runtime.length,sha256:sha256(runtime),width:256,height:256,decodedRGBABytes:256*256*4}};
await writeFile(directory+'/bog-ground.webp',runtime);await writeFile(directory+'/manifest.json',JSON.stringify(manifest,null,2));
await writeFile('src/fjord-play/WetlandAssets.ts','// Generated by scripts/prepare-wetland-assets.mjs.\nexport const wetlandAsset = '+JSON.stringify({path:directory.replace('public/','')+'/bog-ground.webp',...manifest.runtime},null,4)+' as const;\n');
console.log(JSON.stringify(manifest));
