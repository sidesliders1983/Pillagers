import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import assert from 'node:assert/strict';
import { characterSourceInputs } from './character-source-inputs.mjs';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
mkdirSync('public/game-assets/character-sources', { recursive: true });
const entries = [];
for (const [originalPath, originalSha256] of characterSourceInputs()) {
    const original = readFileSync('public' + originalPath);
    assert.equal(sha256(original), originalSha256, 'Original character bytes changed: ' + originalPath);
    const compressed = gzipSync(original, { level: 9 }), hash = sha256(compressed);
    const path = '/game-assets/character-sources/' + hash.slice(0, 20) + '.gz';
    writeFileSync('public' + path, compressed);
    entries.push({ originalPath, originalSha256, originalBytes: original.length,
        path, sha256: hash, bytes: compressed.length });
}
writeFileSync('src/characters/PreparedCharacterCatalog.ts',
    '// Generated by scripts/prepare-character-sources.mjs. Do not edit.\n' +
    'export const preparedCharacterCatalog = ' + JSON.stringify({ version: 1, entries }, null, 4) + ' as const;\n');
const total = field => entries.reduce((sum, entry) => sum + entry[field], 0);
console.log(JSON.stringify({ assets: entries.length, originalBytes: total('originalBytes'),
    preparedBytes: total('bytes'), note: 'No geometry, textures, rig, binding, DNA or LOD changes.' }, null, 2));
