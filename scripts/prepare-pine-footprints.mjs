import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { NodeIO, getBounds } from '@gltf-transform/core';
import { loadTypeScript } from './load-typescript.mjs';

const directory = 'public/nature/ez-tree-pilot/';
const manifest = JSON.parse(await readFile(directory + 'manifest.json', 'utf8'));
const source = manifest.assets.find(asset => asset.size === 'large');
for (const entry of [source, ...source.resources]) {
    const bytes = await readFile(directory + entry.file);
    const actual = createHash('sha256').update(bytes).digest('hex');
    if (actual !== entry.sha256) throw new Error('Changed pinned EZ-Tree source: ' + entry.file);
}
const document = await new NodeIO().read(directory + source.file);
const { min, max } = getBounds(document.getRoot().listScenes()[0]);
const height = max[1] - min[1];
const radius = Math.hypot((max[0] - min[0]) / 2, (max[2] - min[2]) / 2);
const { natureFootprints } = loadTypeScript(new URL('../src/world-generation/NatureFootprints.ts', import.meta.url));
const footprints = {};
for (const id of ['kaykit-conifer-a', 'kaykit-conifer-b', 'kaykit-conifer-c']) {
    const roleHeight = natureFootprints[id].height;
    footprints[id] = { radius: radius * roleHeight / height, height: roleHeight,
        sourceSha256: source.sha256, sourceRevision: manifest.sourceRevision };
}
await writeFile('src/world-generation/PineFootprints.ts',
    '// Generated by scripts/prepare-pine-footprints.mjs from the pinned EZ-Tree Large source.\n' +
    '// Matches LabPines: centered X/Z, grounded Y, normalized to the three KayKit role heights.\n' +
    'export const pineFootprints = ' + JSON.stringify(footprints, null, 4) + ' as const;\n');
console.log(footprints);
